#!/usr/bin/env python3
"""tube-autopilot SETUP WIZARD - connect your 4 YouTube channels in one sitting.

Runs on plain Python (NO pip installs needed). Start it by double-clicking
START-HERE.bat (Windows) or START-HERE.command (Mac), or run:

    python tools/setup_wizard.py                 # guide through all 4 channels
    python tools/setup_wizard.py --verify        # re-check saved connections
    python tools/setup_wizard.py --redo money    # redo one channel only

What it does for each channel (mindset / facts / tech / money):
  1. asks for the OAuth client JSON you downloaded from that channel's
     Google Cloud project (type the file path, or paste the JSON content)
  2. opens your browser -> you sign in with THAT channel's Gmail -> Allow
  3. catches the redirect and exchanges the code for a refresh token
  4. instantly verifies the connection by reading your live YouTube
     channel name + subscriber count
  5. saves everything to factory.env (your private keyring file -
     NEVER upload it anywhere)

When all 4 are green it prints the FACTORY_ENV blob - ONE block you paste
into GitHub as a single repository secret. Optionally paste the same blob
back to your assistant in chat for a pre-flight check before GitHub.

Full click-by-click instructions: SETUP.md (same folder).
"""
from __future__ import print_function

import argparse
import http.server
import json
import sys
