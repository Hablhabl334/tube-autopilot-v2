# ---------------------------------------------------------------- selftest

def selftest():
    # 1. env round-trip
    d = {"YT_CLIENT_ID_MINDSET": "abc.apps.googleusercontent.com",
         "YT_REFRESH_TOKEN_MINDSET": "1//xyz"}
    assert parse_env_text("\n".join("%s=%s" % kv for kv in d.items())) == d
    # 2. client secret parsing
    sample = json.dumps({"installed": {"client_id": "CID", "client_secret": "SEC"}})
    assert _parse_client_secret(sample) == ("CID", "SEC")
    assert _parse_client_secret("not json") is None
    # 3. auth URL shape
    u = _auth_url("CID", "http://localhost:8912")
    q = urllib.parse.parse_qs(urllib.parse.urlparse(u).query)
    assert q["client_id"] == ["CID"]
    assert q["access_type"] == ["offline"]
    assert q["prompt"] == ["consent"]
    assert "youtube.upload" in q["scope"][0] and "youtube.readonly" in q["scope"][0]
    assert q["redirect_uri"] == ["http://localhost:8912"]
    # 4. redirect parsing (query component, as the handler extracts it)
    query = urllib.parse.urlparse("http://localhost:8912/?code=4/AbCd&scope=x").query
    assert "code" in urllib.parse.parse_qs(query)
    # 5. connected-check
    assert channel_connected({"YT_CLIENT_ID_X": "a", "YT_CLIENT_SECRET_X": "b",
                              "YT_REFRESH_TOKEN_X": "c"}, "x") is True
    assert channel_connected({}, "x") is False
    # 6. gmail label with and without the private mapping file
    saved = dict(GMAILS)
    GMAILS.clear()
    assert gmail_label("mindset", "1") == "Gmail #1"
    GMAILS.update({"mindset": "x@gmail.com"})
    assert gmail_label("mindset", "1") == "x@gmail.com"
    GMAILS.clear()
    GMAILS.update(saved)
    print("selftest OK - wizard internals verified")


# -------------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description="tube-autopilot setup wizard")
    ap.add_argument("--verify", action="store_true", help="re-check saved connections")
    ap.add_argument("--redo", metavar="CHANNEL",
                    help="redo one channel: mindset | facts | tech | money")
    ap.add_argument("--selftest", action="store_true", help=argparse.SUPPRESS)
    args = ap.parse_args()

    if args.selftest:
        selftest()
        return 0
    if args.verify:
        return verify_all()

    print("=" * 66)
    print("  TUBE-AUTOPILOT SETUP WIZARD")
    print("  4 YouTube channels -> 1 factory.env keyring -> 1 GitHub secret")
    print("  (detailed screenshots-style help: SETUP.md next to this file)")
    print("=" * 66)

    data = load_env()
    if args.redo:
        ch = args.redo.lower()
        if ch not in [c[0] for c in CHANNELS]:
            print("unknown channel '%s' (use mindset|facts|tech|money)" % ch)
            return 1
        for k in ENV_KEYS:
            data.pop(k.format(CH=ch.upper()), None)
        save_env(data)

    for ch_id, name, project, slot in CHANNELS:
        if channel_connected(data, ch_id) and not args.redo:
            print("  [CONNECTED ] %s - skipping (use --redo %s to redo)"
                  % (name, ch_id))
            continue
        try:
            connect_channel(ch_id, name, project, slot, data)
        except KeyboardInterrupt:
            print("\n  (interrupted - progress is saved; re-run any time)")
            return 1

    print_final()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nbye - re-run any time, progress is saved.")
        sys.exit(1)
